/* ============================================================
   The completion certificate.

   Drawn on a canvas from the progress already in this browser. There is
   no server in this file and no upload: the name you type never leaves
   the page, and the PNG is produced by your own machine.

   Reads window.RUST_COURSE (published by app.js) and window.PY_COURSE
   (generated by tools/pybuild.py), so the totals can never drift from
   the curriculum.
   ============================================================ */
(function () {
  "use strict";

  const NAME_KEY = "rusty-cert-name";

  /* The mascots, loaded as images so the seal is really Rusty and Monty
     rather than whichever emoji the printer happens to have. Falls back
     to the emoji if the SVG cannot be loaded. */
  const mascotImages = {};   // id -> Image, or null once we know it failed
  const mascotPending = {};  // id -> true only while a load is in flight

  function loadMascot(id, src, onReady) {
    // Settled? Hand back the result (which may legitimately be null).
    // `hasOwnProperty` rather than a truthiness or !== undefined check:
    // an unsettled entry and a failed one both read as falsy, and
    // confusing them means starting a fresh load on every single draw.
    // Since a completed load triggers a redraw, that is an infinite loop.
    if (Object.prototype.hasOwnProperty.call(mascotImages, id)) return mascotImages[id];
    if (mascotPending[id]) return undefined;
    mascotPending[id] = true;
    const img = new Image();
    img.onload = () => { mascotImages[id] = img; delete mascotPending[id]; onReady(); };
    img.onerror = () => { mascotImages[id] = null; delete mascotPending[id]; onReady(); };
    img.src = src;
    return undefined;
  }

  const SCHOOLS = {
    rust: {
      id: "rust",
      name: "The Rusty School",
      subject: "Rust",
      art: "assets/ferris.svg",
      seal: "🦀",
      ink: "#f74c00",
      inkSoft: "#ffb454",
      paper: "#fffaf5",
      line: "#e6d5c4",
      text: "#241a12",
      muted: "#6b5847",
      mascot: "Rusty",
      title: "Certified Rustacean",
    },
    python: {
      id: "python",
      name: "The Python School",
      subject: "Python",
      art: "python/assets/monty.svg",
      seal: "🐍",
      ink: "#2b6ea0",
      inkSoft: "#ffde57",
      paper: "#f7fbff",
      line: "#cfe0ee",
      text: "#0f1c27",
      muted: "#4d6274",
      mascot: "Monty",
      title: "Certified Pythonista",
    },
  };

  function getDone() {
    try { return new Set(JSON.parse(localStorage.getItem("rusty-done") || "[]")); }
    catch { return new Set(); }
  }

  /* What each school requires, and how far along this browser is. */
  function statusFor(id) {
    const done = getDone();
    const has = (x) => done.has(x);
    if (id === "rust") {
      const c = window.RUST_COURSE;
      if (!c) return null;
      const lessons = c.lessons.filter((l) => has(l.id)).length;
      const projects = c.projects.filter((p) => has(p.id)).length;
      let puzzles = 0;
      done.forEach((d) => { if (d.startsWith("dojo-")) puzzles++; });
      return {
        school: SCHOOLS.rust,
        lessons, lessonTotal: c.lessons.length,
        projects, projectTotal: c.projects.length,
        puzzles, puzzleTotal: c.dojoTotal,
        complete: lessons >= c.lessons.length,
      };
    }
    const c = window.PY_COURSE;
    if (!c) return null;
    const lessons = c.lessons.filter((l) => has(l.id)).length;
    const projects = c.projects.filter((p) => has(p.id)).length;
    let puzzles = 0;
    done.forEach((d) => { if (d.startsWith("pypit-")) puzzles++; });
    return {
      school: SCHOOLS.python,
      lessons, lessonTotal: c.lessons.length,
      projects, projectTotal: c.projects.length,
      puzzles, puzzleTotal: c.pitTotal,
      complete: lessons >= c.lessons.length,
    };
  }

  /* ---------------- drawing ---------------- */
  function roundRect(ctx, x, y, w, h, r) {
    ctx.beginPath();
    ctx.moveTo(x + r, y);
    ctx.arcTo(x + w, y, x + w, y + h, r);
    ctx.arcTo(x + w, y + h, x, y + h, r);
    ctx.arcTo(x, y + h, x, y, r);
    ctx.arcTo(x, y, x + w, y, r);
    ctx.closePath();
  }

  function draw(canvas, state, name, onArtReady) {
    const s = state.school;
    const ctx = canvas.getContext("2d");
    const W = canvas.width, H = canvas.height;
    const sans = '"Segoe UI", system-ui, -apple-system, Helvetica, Arial, sans-serif';

    ctx.clearRect(0, 0, W, H);

    // paper
    ctx.fillStyle = s.paper;
    ctx.fillRect(0, 0, W, H);

    // a soft wash of the school colour in the corners
    const g = ctx.createRadialGradient(W / 2, H * 0.12, 40, W / 2, H * 0.12, W * 0.75);
    g.addColorStop(0, s.ink + "18");
    g.addColorStop(1, s.ink + "00");
    ctx.fillStyle = g;
    ctx.fillRect(0, 0, W, H);

    // double rule border
    ctx.strokeStyle = s.ink;
    ctx.lineWidth = 7;
    roundRect(ctx, 42, 42, W - 84, H - 84, 20);
    ctx.stroke();
    ctx.strokeStyle = s.line;
    ctx.lineWidth = 2.5;
    roundRect(ctx, 62, 62, W - 124, H - 124, 14);
    ctx.stroke();

    ctx.textAlign = "center";

    // school name
    ctx.fillStyle = s.ink;
    ctx.font = "700 34px " + sans;
    ctx.letterSpacing = "6px";
    ctx.fillText(s.name.toUpperCase(), W / 2, 150);
    ctx.letterSpacing = "0px";

    // rule under the school name
    ctx.strokeStyle = s.line;
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.moveTo(W / 2 - 190, 172);
    ctx.lineTo(W / 2 + 190, 172);
    ctx.stroke();

    // headline
    ctx.fillStyle = s.text;
    ctx.font = "800 78px " + sans;
    ctx.fillText("Certificate of Completion", W / 2, 268);

    ctx.fillStyle = s.muted;
    ctx.font = "400 30px " + sans;
    ctx.fillText("This is to certify that", W / 2, 344);

    // the name, shrunk to fit rather than overflowing the paper
    const displayName = (name || "").trim() || "A Determined Beginner";
    let size = 96;
    ctx.font = "700 " + size + "px " + sans;
    while (ctx.measureText(displayName).width > W - 320 && size > 34) {
      size -= 3;
      ctx.font = "700 " + size + "px " + sans;
    }
    ctx.fillStyle = s.text;
    ctx.fillText(displayName, W / 2, 446);

    // signature-style rule under the name
    ctx.strokeStyle = s.ink;
    ctx.lineWidth = 3;
    ctx.beginPath();
    ctx.moveTo(W / 2 - 330, 478);
    ctx.lineTo(W / 2 + 330, 478);
    ctx.stroke();

    // what they did
    ctx.fillStyle = s.muted;
    ctx.font = "400 30px " + sans;
    ctx.fillText("has completed every lesson of", W / 2, 536);
    ctx.fillStyle = s.ink;
    ctx.font = "700 52px " + sans;
    ctx.fillText(s.subject + " from Zero", W / 2, 596);
    ctx.fillStyle = s.muted;
    ctx.font = "400 27px " + sans;
    ctx.fillText(
      "starting from no programming experience whatsoever",
      W / 2, 642
    );

    // the tally
    const stats = [
      [state.lessons + " / " + state.lessonTotal, "lessons"],
      [state.projects + " / " + state.projectTotal, "projects built"],
      [state.puzzles + " / " + state.puzzleTotal, "puzzles solved"],
    ];
    const boxW = 300, boxH = 118, gap = 34;
    const totalW = stats.length * boxW + (stats.length - 1) * gap;
    let bx = (W - totalW) / 2;
    stats.forEach(([big, small]) => {
      ctx.fillStyle = s.ink + "0e";
      roundRect(ctx, bx, 692, boxW, boxH, 14);
      ctx.fill();
      ctx.strokeStyle = s.line;
      ctx.lineWidth = 2;
      roundRect(ctx, bx, 692, boxW, boxH, 14);
      ctx.stroke();
      ctx.fillStyle = s.ink;
      ctx.font = "800 44px " + sans;
      ctx.fillText(big, bx + boxW / 2, 746);
      ctx.fillStyle = s.muted;
      ctx.font = "400 22px " + sans;
      ctx.fillText(small, bx + boxW / 2, 782);
      bx += boxW + gap;
    });

    // seal. Everything below here has to stay inside the inner rule,
    // whose bottom edge sits at H - 62.
    const cx = W / 2, cy = 878, r = 60;
    ctx.beginPath();
    ctx.arc(cx, cy, r, 0, Math.PI * 2);
    ctx.fillStyle = s.ink + "12";
    ctx.fill();
    ctx.strokeStyle = s.ink;
    ctx.lineWidth = 4;
    ctx.stroke();
    ctx.beginPath();
    ctx.arc(cx, cy, r - 11, 0, Math.PI * 2);
    ctx.strokeStyle = s.inkSoft;
    ctx.lineWidth = 2;
    ctx.stroke();
    const art = loadMascot(s.id, s.art, onArtReady || function () {});
    if (art) {
      // fit the mascot inside the seal, keeping its aspect ratio
      const box = (r - 20) * 2;
      const scale = Math.min(box / art.width, box / art.height);
      const w = art.width * scale, h = art.height * scale;
      ctx.drawImage(art, cx - w / 2, cy - h / 2, w, h);
    } else {
      ctx.font = "56px " + sans;
      ctx.textBaseline = "middle";
      ctx.fillText(s.seal, cx, cy + 3);
      ctx.textBaseline = "alphabetic";
    }

    // title ribbon under the seal
    ctx.fillStyle = s.ink;
    ctx.font = "700 30px " + sans;
    ctx.letterSpacing = "3px";
    ctx.fillText(s.title.toUpperCase(), cx, 974);
    ctx.letterSpacing = "0px";

    ctx.fillStyle = s.muted;
    ctx.font = "400 20px " + sans;
    ctx.fillText(
      "Awarded by " + s.mascot + ", who has read your code and is quietly impressed.",
      cx, 1010
    );

    // footer: date on the left, where it came from on the right
    ctx.font = "400 24px " + sans;
    const date = new Date().toLocaleDateString(undefined, {
      year: "numeric", month: "long", day: "numeric",
    });
    ctx.textAlign = "left";
    ctx.fillText(date, 112, 1046);
    ctx.textAlign = "right";
    ctx.fillText("rustyschool.com", W - 112, 1046);
    ctx.textAlign = "center";
  }

  /* ---------------- page ---------------- */
  function el(tag, cls, text) {
    const e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  function render() {
    const root = document.getElementById("cert-root");
    const stage = document.getElementById("cert-stage");
    const canvas = document.getElementById("cert-canvas");
    if (!root || !canvas) return;

    const states = ["rust", "python"].map(statusFor).filter(Boolean);
    if (!states.length) {
      root.innerHTML = "";
      const card = el("div", "card");
      card.appendChild(el("p", "muted", "Could not read the curriculum. Try reloading the page."));
      root.appendChild(card);
      return;
    }

    const earned = states.filter((s) => s.complete);
    root.innerHTML = "";

    if (!earned.length) {
      stage.hidden = true;
      const card = el("div", "card");
      card.style.maxWidth = "640px";
      card.appendChild(el("h3", null, "Not yet, but you can see it from here"));
      card.appendChild(el("p", "muted",
        "A certificate unlocks when every lesson in a school is marked complete. " +
        "Here is where this browser stands:"));
      const list = el("div", "cert-progress");
      states.forEach((s) => {
        const row = el("div", "cert-row");
        row.appendChild(el("span", "cert-row-seal", s.school.seal));
        const body = el("div");
        body.appendChild(el("strong", null, s.school.name));
        const bar = el("div", "progress-bar");
        const fill = el("div", "progress-fill");
        fill.style.width = Math.round((s.lessons / s.lessonTotal) * 100) + "%";
        bar.appendChild(fill);
        body.appendChild(bar);
        body.appendChild(el("span", "muted small",
          s.lessons + " of " + s.lessonTotal + " lessons complete" +
          (s.lessons ? "" : ", so this is the perfect moment to start")));
        row.appendChild(body);
        list.appendChild(row);
      });
      card.appendChild(list);
      // Point them at whichever school they are furthest through, since
      // that is the one they are most likely to finish first.
      const ahead = states.slice().sort(
        (a, b) => (b.lessons / b.lessonTotal) - (a.lessons / a.lessonTotal))[0];
      const cta = el("a", "btn btn-primary btn-small",
        "Continue " + ahead.school.subject + " →");
      cta.href = ahead.school.id === "python" ? "python/learn/index.html" : "learn/index.html";
      cta.style.marginTop = "14px";
      card.appendChild(cta);
      root.appendChild(card);
      return;
    }

    // At least one school is finished: show the controls.
    stage.hidden = false;
    let current = earned[0];
    const card = el("div", "card cert-controls");
    card.style.maxWidth = "640px";

    if (earned.length > 1) {
      const pickWrap = el("div", "cert-field");
      pickWrap.appendChild(el("label", null, "Which certificate?"));
      const chips = el("div", "cert-chips");
      earned.forEach((s, i) => {
        const b = el("button", "cs-chip" + (i === 0 ? " active" : ""),
          s.school.seal + " " + s.school.subject);
        b.type = "button";
        b.dataset.school = s.school.id;
        b.addEventListener("click", () => {
          chips.querySelectorAll("button").forEach((x) => x.classList.toggle("active", x === b));
          current = s;
          redraw();
        });
        chips.appendChild(b);
      });
      pickWrap.appendChild(chips);
      card.appendChild(pickWrap);
    }

    const nameWrap = el("div", "cert-field");
    const label = el("label", null, "The name to print");
    label.setAttribute("for", "cert-name");
    nameWrap.appendChild(label);
    const input = el("input", "cert-input");
    input.id = "cert-name";
    input.type = "text";
    input.maxLength = 60;
    input.placeholder = "However you want to be known";
    input.value = localStorage.getItem(NAME_KEY) || "";
    input.autocomplete = "off";
    nameWrap.appendChild(input);
    nameWrap.appendChild(el("span", "muted small",
      "Stored only in this browser, and only so you do not have to type it twice."));
    card.appendChild(nameWrap);

    const actions = el("div", "cta-row");
    const dl = el("button", "btn btn-primary btn-small", "Download PNG");
    dl.type = "button";
    const pr = el("button", "btn btn-ghost btn-small", "Print");
    pr.type = "button";
    actions.appendChild(dl);
    actions.appendChild(pr);
    card.appendChild(actions);
    root.appendChild(card);

    function redraw() {
      // The mascot may still be loading on the first pass; when it
      // arrives, draw once more so the seal is not left empty.
      draw(canvas, current, input.value, () => draw(canvas, current, input.value));
    }

    input.addEventListener("input", () => {
      localStorage.setItem(NAME_KEY, input.value);
      redraw();
    });

    dl.addEventListener("click", () => {
      redraw();
      canvas.toBlob((blob) => {
        if (!blob) return;
        const url = URL.createObjectURL(blob);
        const a = document.createElement("a");
        a.href = url;
        a.download = "rusty-school-" + current.school.id + "-certificate.png";
        document.body.appendChild(a);
        a.click();
        a.remove();
        setTimeout(() => URL.revokeObjectURL(url), 4000);
      }, "image/png");
    });

    pr.addEventListener("click", () => { redraw(); window.print(); });

    redraw();
  }

  // app.js publishes RUST_COURSE on parse and course.js sets PY_COURSE;
  // both are deferred, so DOMContentLoaded is late enough for each.
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", render);
  } else {
    render();
  }
})();
